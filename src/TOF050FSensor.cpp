TOF050FSensor::TOF050FSensor() {

    tofSerial = new HardwareSerial(0);
}

TOF050FSensor::~TOF050FSensor() {
    if (tofSerial) {
        delete tofSerial;
    }
}

bool TOF050FSensor::begin() {
    Serial.println("TOF050F传感器开始初始化...");
    Serial.printf("使用引脚: RX=%d, TX=%d, 波特率=%d\n", TOF050F_RX_PIN, TOF050F_TX_PIN, TOF050F_BAUD_RATE);

    tofSerial->begin(TOF050F_BAUD_RATE, SERIAL_8N1, TOF050F_RX_PIN, TOF050F_TX_PIN);

    while (tofSerial->available()) {
        tofSerial->read();
    }

    rxRdIndex = 0;
    rxWrIndex = 0;
    lastRxTimestamp = 0;
    timCount = 0;
    lastDistance = -1;
    sensorValid = false;
    newDataAvailable = false;

    Serial.println("TOF050F传感器初始化完成");

    delay(100);
    return true;
}

int16_t TOF050FSensor::readDistance() {
    uint8_t testBuff[20];

    testBuff[0] = 0;
    testBuff[1] = 3;
    testBuff[2] = REG_RD_ADDR >> 8;
    testBuff[3] = REG_RD_ADDR;
    testBuff[4] = 0;
    testBuff[5] = 1;

    uart_tpm_tx_data(0, testBuff, 6);

    delay(50);
    update();

    return lastDistance;
}

void TOF050FSensor::setContinuousOutput(uint16_t interval_ms) {
    uint8_t testBuff[20];

    testBuff[0] = 0;
    testBuff[1] = 6;
    testBuff[2] = REG_WR_ADDR >> 8;
    testBuff[3] = REG_WR_ADDR;
    testBuff[4] = interval_ms >> 8;
    testBuff[5] = interval_ms;

    uart_tpm_tx_data(0, testBuff, 6);
}

void TOF050FSensor::stopContinuousOutput() {
    setContinuousOutput(0);
}

void TOF050FSensor::update() {
    uart_tpm_main();
}

bool TOF050FSensor::hasNewData() {
    return newDataAvailable;
}

int16_t TOF050FSensor::getLastDistance() {
    newDataAvailable = false;
    return lastDistance;
}

bool TOF050FSensor::isValid() {
    return sensorValid;
}

uint16_t TOF050FSensor::crc16_calculate_modbus(uint8_t *p_data, uint16_t len) {
    uint8_t crchi = 0xff;
    uint8_t crclo = 0xff;
    uint16_t index;
    while (len--) {
        index = crclo ^ *p_data++;
        crclo = crchi ^ crc16mTableHi[index];
        crchi = crc16mTableLo[index];
    }
    return (crchi << 8 | crclo);
}

uint16_t TOF050FSensor::uart_read_isr(uint8_t channel, uint8_t *p_buff) {
    uint16_t i = 0, wrIndex = 0;
    for (wrIndex = rxWrIndex; wrIndex != rxRdIndex; rxRdIndex = (rxRdIndex + 1) % 80, i++) {
        p_buff[i] = rxBuffer[rxRdIndex];
    }
    return i;
}

uint8_t TOF050FSensor::uart_tpm_rx_isr(uint8_t channel, uint8_t data) {
    if (rxRdIndex == ((rxWrIndex + 1) % 80)) {
        return 1;
    } else {
        rxBuffer[rxWrIndex] = data;
        rxWrIndex = (rxWrIndex + 1) % 80;
    }
    lastRxTimestamp = tim_get_count();
    return 0;
}

void TOF050FSensor::uart_tpm_main(void) {
    uint16_t rxLen = 0;
    uint16_t crc16 = 0;
    uint8_t tempBuff[80];

    while (tofSerial->available()) {
        uint8_t data = tofSerial->read();
        uart_tpm_rx_isr(0, data);
    }

    if (tim_check_timeout(lastRxTimestamp, tim_get_count(), frameTimeInvt)) {
        rxLen = uart_read_isr(0, tempBuff);
        if (rxLen > 2) {
            crc16 = tempBuff[rxLen - 1];
            crc16 <<= 8;
            crc16 |= tempBuff[rxLen - 2];
            if (crc16 == crc16_calculate_modbus(tempBuff, rxLen - 2)) {
                modbus_recv_data(tempBuff, rxLen - 2);
            }
        }
        lastRxTimestamp = tim_get_count();
    }
}

uint8_t TOF050FSensor::uart_tpm_tx_data(uint8_t channel, uint8_t *p_data, uint16_t len) {
    uint16_t crc16 = 0;
    if (NULL == p_data || 0 == len || len + 2 > 80) {
        return 1;
    }
    memcpy(txBuffer, p_data, len);
    crc16 = crc16_calculate_modbus(txBuffer, len);
    txBuffer[len] = crc16;
    txBuffer[len + 1] = crc16 >> 8;
    tofSerial->write(txBuffer, len + 2);
    return 1;
}

void TOF050FSensor::modbus_recv_data(uint8_t *p_data, uint16_t len) {

    if (len >= 5 && p_data[1] == 3) {
        uint16_t distance = p_data[3];
        distance <<= 8;
        distance |= p_data[4];

        if (distance != 0xFFFF) {
            lastDistance = distance;
            sensorValid = true;
            newDataAvailable = true;

        } else {
            sensorValid = false;

        }
    } else {
        Serial.println("TOF050F数据格式不正确");
    }
}

uint32_t TOF050FSensor::tim_get_count(void) {
    return millis() / 2;
}

uint8_t TOF050FSensor::tim_check_timeout(uint32_t start, uint32_t now, uint32_t invt) {
    if ((uint32_t)(start + invt) >= start) {
        if ((now >= (uint32_t)(start + invt)) || (now < start)) {
            return 1;
        }
    } else {
        if ((now < start) && (now >= (uint32_t)(start + invt))) {
            return 1;
        }
    }
    return 0;
}
